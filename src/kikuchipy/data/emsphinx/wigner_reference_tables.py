"""Mathematica reference values of the Wigner (lowercase) d function
and its first two derivatives with respect to beta.

This module and documentation is only relevant for kikuchipy
developers, not for users.

.. warning:
    This module and its submodules are for internal use only.  Do not
    use them in your own code. We may change the API at any time with
    no warning.

The tables are the ones EMSphInx' own unit test ``test/sht/wigner.cpp``
compares its implementation against, transcribed verbatim (32
significant digits, the ``L`` suffix of the C++ ``long double``
literals dropped) with a throw-away regular expression parser. Python
parses the literals correctly rounded, which is at least as good as the
``long double`` to ``double`` cast the C++ test performs.

The Mathematica expressions which produced them, quoted from
``wigner.cpp`` lines 116, 568 and 379:

- ``N[Table[WignerD[{j, k, m}, beta], {j, 0, 4}, {k, -4, 4},
  {m, -4, 4}], 32]`` for ``beta`` = ``Pi/2`` (``tab12``, lines
  120-173), ``Pi/3`` (``tab13``, lines 176-229) and ``2 Pi/3``
  (``tab23``, lines 232-284).
- ``Table[If[Max[Abs[k], Abs[m]] > j, NAN,
  D[WignerD[{j, k, m}, beta], {beta, 1}]], {j, 0, 4}, {k, -4, 4},
  {m, -4, 4}]`` for ``beta`` = ``Pi/3`` (``tab13_1``, lines 573-625)
  and ``2 Pi/3`` (``tab23_1``, lines 628-680), and the same with
  ``{beta, 2}`` for the second derivative (``tab13_2``, lines 683-735,
  and ``tab23_2``, lines 738-790).
- ``WignerD[{3, 2, 1}, Pi/6, Pi/2, Pi/3]`` (``d321``, line 379), the
  single Wigner (uppercase) D value, in Mathematica's
  ``WignerD[{j, k, m}, gamma, beta, alpha]`` argument order.

Each of the seven tables holds the ``165`` entries defined by
``|k| <= j`` and ``|m| <= j`` for ``j`` in ``[0, 5)``; the remaining
``240`` slots of the ``5 x 9 x 9`` C++ array are ``NAN`` and are
implied, not stored. Use :func:`as_array` for the dense array with the
NaN slots restored.

Note that this is the Fukushima/Mathematica convention
``d^j_{k,m}(beta) = WignerD[{j, k, m}, beta]``, which is the transpose
of the Wikipedia/Varshalovich small d, see
:mod:`kikuchipy.indexing._spherical._wigner`.
"""

